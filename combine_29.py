import pandas as pd, os
r20 = pd.read_csv("reports/final_decision_20_coins.csv")
r9  = pd.read_csv("reports/final_decision_new_9_coins.csv")
r9 = r9.rename(columns={'First':'First','Last':'Last'})
all_coins = pd.concat([r20, r9], ignore_index=True)
all_coins = all_coins.sort_values('Return', ascending=False)
all_coins.to_csv("reports/final_decision_29_coins.csv", index=False)
print(f"Total coins: {len(all_coins)}")
print(f"KEEP: {(all_coins.Decision=='KEEP').sum()}")
print(f"DROP: {(all_coins.Decision=='DROP').sum()}")
print("\n=== TOP 15 ===")
print(all_coins.head(15).to_string(index=False))
print("\n=== DROP ===")
print(all_coins[all_coins.Decision=='DROP'].to_string(index=False))
